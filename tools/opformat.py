# -*- coding: utf-8 -*-
"""完整的 DEX opcode → 指令长度（code unit 数）映射。"""

SIZE = {}


def _set(fmt, ops):
    for o in ops:
        assert o not in SIZE, f'opcode 0x{o:02x} 重复赋值'
        SIZE[o] = fmt


_set(1, [0x00, 0x0e, 0x73, *range(0x3e, 0x44), *range(0xe3, 0xfa)])
_set(1, [0x01, 0x04, 0x07, 0x21, 0x7b, 0x7c, 0x7d, 0x7e, 0x7f, 0x80, 0x81, 0x82, 0x83])
_set(2, [0x02, 0x05, 0x08])
_set(3, [0x03, 0x06, 0x09])
_set(1, [*range(0x0a, 0x0e), *range(0x0f, 0x12)])
_set(1, [0x12])
_set(2, [0x13, 0x16])
_set(3, [0x14, 0x17])
_set(2, [0x15, 0x19])
_set(5, [0x18])
_set(2, [0x1a, 0x1c, 0x1f, 0x22, 0xfe, 0xff])
_set(3, [0x1b])
_set(1, [0x1d, 0x1e, 0x27])
_set(2, [0x20, 0x23])
_set(3, [0x24, 0x25, 0xfc, 0xfd])
_set(3, [0x26, 0x2b])
_set(1, [0x28])
_set(2, [0x29])
_set(3, [0x2a])
_set(2, [0x2c])
_set(2, list(range(0x2d, 0x32)))
_set(2, list(range(0x32, 0x38)))
_set(2, list(range(0x38, 0x3e)))
_set(2, list(range(0x44, 0x52)))
_set(2, list(range(0x52, 0x60)))
_set(2, list(range(0x60, 0x6e)))
_set(3, list(range(0x6e, 0x73)))
_set(3, list(range(0x74, 0x79)))
_set(1, [0x79, 0x7a, *range(0x84, 0x90)])
_set(2, list(range(0x90, 0xb0)))
_set(1, list(range(0xb0, 0xd0)))
_set(2, list(range(0xd0, 0xd8)))
_set(2, list(range(0xd8, 0xe3)))
_set(4, [0xfa, 0xfb])
